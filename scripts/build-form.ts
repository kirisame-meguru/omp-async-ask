// Release preparation: compile the host's JSX form UI, keeping host services external.
import { isBuiltin } from "node:module";
import { dirname, join, relative, resolve } from "node:path";

const version = "19.2.1";
const root = join(import.meta.dir, "..");
const host = join(root, "node_modules/@oh-my-pi/pi-coding-agent");
const source = join(host, "src");
const manifest = await Bun.file(join(host, "package.json")).json();
if (manifest.version !== version) throw new Error(`Expected pi-coding-agent@${version}`);
const result = await Bun.build({
	entrypoints: [join(source, "ui/forms/html-form/index.ts")],
	external: ["@oh-my-pi/*"],
	target: "bun", format: "esm", root, metafile: true,
	jsx: { runtime: "automatic", development: false },
	plugins: [{ name: "host-form-services", setup(build) {
		build.onResolve({ filter: /^\.\.?\// }, ({ path, importer }) => {
			const target = resolve(dirname(importer), path);
			const subpath = relative(source, target).replaceAll("\\", "/");
			// These named wildcard exports are retained in the compiled host registry.
			// In particular, never bundle a second keybinding/configuration singleton.
			if (/^(?:config|modes|tools|utils)\//.test(subpath)) {
				return { path: `@oh-my-pi/pi-coding-agent/${subpath.replace(/\.tsx?$/, "")}`, external: true };
			}
		});
	} }],
});
if (!result.success) throw new AggregateError(result.logs, "Unable to compile native form UI");
if (result.outputs.length !== 1 || !result.metafile) throw new Error("Expected one native form module");
for (const path of Object.keys(result.metafile.inputs)) {
	if (!path.replaceAll("\\", "/").includes("node_modules/@oh-my-pi/pi-coding-agent/src/ui/")) {
		throw new Error(`Unexpected bundled dependency: ${path}`);
	}
}
const output = await result.outputs[0]!.text();
for (const reference of new Bun.Transpiler({ loader: "js" }).scanImports(output)) {
	if (!isBuiltin(reference.path) && !reference.path.startsWith("@oh-my-pi/")) {
		throw new Error(`Unexpected form runtime dependency: ${reference.path}`);
	}
}
const license = (await Bun.file(join(host, "LICENSE")).text()).trim().replaceAll("\r\n", "\n");
const header = `/* Generated by bun run build:form from OMP ${version}. Do not hand edit.\n${license}\n*/\n`;
if (Buffer.byteLength(header + output) > 256 * 1024) throw new Error("Unexpected native form bundle growth");
await Bun.write(join(root, "src/form.generated.mjs"), header + output);
console.log(`Compiled OMP ${version} native form UI: ${Buffer.byteLength(header + output)} bytes`);
